/** Список банков для UI: [{ id, label, count }]. */
function listBanks() {
  return Object.entries(BANKS).map(([id, b]) => ({
    id, label: b.label, count: b.questions.length,
  }));
}

/** Текст встроенного вопроса по ключу `b:<bankId>:<index>` или null. */
function builtinText(key) {
  const m = /^b:([a-z]+):(\d+)$/.exec(key || '');
  if (!m) return null;
  const bank = BANKS[m[1]];
  if (!bank) return null;
  return bank.questions[Number(m[2])] ?? null;
}

/** Все ключи выбранных банков: ['b:family:0', ...]. Неизвестные банки игнорируются. */
function keysForBanks(bankIds) {
  const out = [];
  for (const id of bankIds || []) {
    const bank = BANKS[id];
    if (!bank) continue;
    for (let i = 0; i < bank.questions.length; i++) out.push(`b:${id}:${i}`);
  }
  return out;
}

module.exports = { BANKS, listBanks, builtinText, keysForBanks };
