/**
 * Ошибки API: общие предикаты.
 *
 * `api/client.ts` реджектит `Error` с полем `status` (HTTP-код) и текстом от
 * сервера. Сырой серверный текст показывать пользователю нельзя: он всегда на
 * английском («Forbidden»), не переводится и в момент смены токена вообще не
 * описывает реальную проблему.
 *
 * Транзиентные 401/403 возникают в узком окне между логаутом/логином и
 * обновлением токена (и раньше — из-за неверной identity, см. QA-прогон
 * 2026-09-03). Единый предикат нужен, чтобы каждый новый загрузчик не заводил
 * свою копию этой проверки и не «залипал» с сырым текстом на экране.
 */
export function isAuthError(e: unknown): boolean {
  const status = (e as { status?: number } | null)?.status;
  return status === 401 || status === 403;
}
